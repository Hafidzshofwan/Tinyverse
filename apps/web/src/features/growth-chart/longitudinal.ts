/**
 * Cara ukur panjang/tinggi badan.
 * "pb" = panjang badan, diukur telentang (infantometer).
 * "tb" = tinggi badan, diukur berdiri (stadiometer).
 *
 * WHO memilih tabel berdasarkan CARA UKUR, bukan umur. Umur hanya dipakai untuk
 * menebak nilai awal pilihan ini di antarmuka; pengguna yang memutuskan.
 */
export type CaraUkurPanjang = "pb" | "tb";

/** Umur (bulan) tempat WHO berpindah dari ukur telentang ke ukur berdiri. */
export const BATAS_BULAN_CARA_UKUR = 24;

/** Tebakan awal cara ukur dari umur. Hanya untuk nilai bawaan antarmuka. */
export function caraUkurDariUsia(usiaBulan: number): CaraUkurPanjang {
  return usiaBulan < BATAS_BULAN_CARA_UKUR ? "pb" : "tb";
}

/** Tabel WHO yang sesuai untuk kombinasi jenis kelamin dan cara ukur. */
export function tabelBbPbTb(jk: Gender, cara: CaraUkurPanjang): ZscoreTable {
  if (cara === "pb") {
    return jk === "female" ? WHO_BBPB_FEMALE_45_110 : WHO_BBPB_MALE_45_110;
  }
  return jk === "female" ? WHO_BBTB_FEMALE_65_120 : WHO_BBTB_MALE_65_120;
}

export interface HasilBbPbTb {
  /** Z-score berat badan menurut panjang/tinggi badan. */
  z: number;
  /** Tabel yang benar-benar dipakai. */
  cara: CaraUkurPanjang;
  /** true bila panjang/tinggi di luar rentang tabel, sehingga z TIDAK sahih. */
  diLuarTabel: boolean;
  /** Rentang sahih tabel tersebut, dalam sentimeter. */
  rentang: [number, number];
}

/**
 * Menghitung z-score BB/PB atau BB/TB memakai tabel WHO yang sesungguhnya.
 *
 * Mengembalikan null bila masukan tidak masuk akal. Bila panjang/tinggi berada
 * di luar rentang tabel, hasil tetap dikembalikan tetapi diLuarTabel bernilai
 * true -- pemanggil WAJIB memeriksanya, karena tkInterpolasiZscoreRow menjepit
 * nilai di luar tabel ke baris tepi sehingga angkanya menyesatkan.
 */
export function hitungZBbPbTb(
  tinggiCm: number,
  bb: number,
  jk: Gender,
  cara: CaraUkurPanjang
): HasilBbPbTb | null {
  if (!Number.isFinite(tinggiCm) || !Number.isFinite(bb)) return null;
  if (tinggiCm <= 0 || bb <= 0) return null;

  const tabel = tabelBbPbTb(jk, cara);
  const kunci = Object.keys(tabel)
    .map((k) => Number(k))
    .filter((k) => Number.isFinite(k))
    .sort((a, b) => a - b);
  const lo = kunci[0] ?? 0;
  const hi = kunci[kunci.length - 1] ?? 0;

  const row = tkInterpolasiZscoreRow(tabel, tinggiCm);
  if (!row) return null;

  return {
    z: Math.round(tkHitungZscoreNumerik(row, bb) * 100) / 100,
    cara,
    diLuarTabel: tkUsiaDiLuarTabel(tabel, tinggiCm),
    rentang: [lo, hi],
  };
}

export function hitungAllZscores(
  usiaBulan: number,
  bb: number,
  tb: number,
  jk: Gender = "male",
  caraUkur?: CaraUkurPanjang
): { bbuZ: number; tbuZ: number; bbtbZ: number | undefined; imtuZ: number } {
  const tableBBU = jk === "female" ? WHO_BBU_FEMALE_0_60 : WHO_BBU_MALE_0_60;
  const tableTBU = jk === "female" ? WHO_TBU_FEMALE_0_60 : WHO_TBU_MALE_0_60;
  const tableIMTU = jk === "female" ? WHO_IMTU_FEMALE_0_60 : WHO_IMTU_MALE_0_60;

  const rowBBU = tkInterpolasiZscoreRow(tableBBU, usiaBulan);
  const rowTBU = tkInterpolasiZscoreRow(tableTBU, usiaBulan);
  const rowIMTU = tkInterpolasiZscoreRow(tableIMTU, usiaBulan);

  const bbuZ = rowBBU ? Math.round(tkHitungZscoreNumerik(rowBBU, bb) * 100) / 100 : 0;
  const tbuZ = rowTBU ? Math.round(tkHitungZscoreNumerik(rowTBU, tb) * 100) / 100 : 0;

  const imtVal = hitungIMT(bb, tb);
  const imtuZ = rowIMTU && imtVal !== null ? Math.round(tkHitungZscoreNumerik(rowIMTU, imtVal) * 100) / 100 : 0;

  // BB/PB atau BB/TB dari tabel WHO yang sesungguhnya.
  //
  // Sebelumnya nilai ini dikarang dengan rumus (bbuZ - tbuZ * 0.5). Rumus itu
  // tidak ada dalam standar WHO mana pun dan tidak pernah menyentuh tabel berat
  // menurut panjang/tinggi, sehingga angkanya tidak bermakna klinis.
  //
  // bbtbZ sengaja dibiarkan undefined bila panjang/tinggi di luar rentang tabel.
  // Mengisinya dengan 0 akan terbaca sebagai "tepat median" -- justru kebalikan
  // dari kenyataan bahwa nilainya tidak diketahui.
  const cara = caraUkur ?? caraUkurDariUsia(usiaBulan);
  const hasilBbtb = hitungZBbPbTb(tb, bb, jk, cara);
  const bbtbZ =
    hasilBbtb && !hasilBbtb.diLuarTabel ? hasilBbtb.z : undefined;

  return { bbuZ, tbuZ, bbtbZ, imtuZ };
}

/** Konversi Z-score ke pita persentil utama WHO */
export function zscoreToPercentileChannel(z: number): number {
  if (z >= 1.88) return 97;
  if (z >= 1.04) return 85;
  if (z >= -0.13) return 50;
  if (z >= -1.04) return 15;
  if (z >= -1.88) return 3;
  return 1; // <3rd
}

export function zscoreToPercentileLabel(z: number): string {
  const p = zscoreToPercentileChannel(z);
  if (p === 1) return "< Percentile 3rd";
  return `Percentile ~${p}th`;
}

